# Version updated to support resizing; recommended when the modeling file has been adjusted.
import argparse
import json
from pathlib import Path

import torch
from transformers import AutoTokenizer
from step_audio2_model.configuration_step_audio_2 import StepAudio2Config
from step_audio2_model.modeling_step_audio_2 import StepAudio2ForCausalLM


# BPE vocabulary information.
AUDIO_BASE_SIZE = 6656       # Number of original audio base units (0..6655).

# Start position of audio base units in the LLM vocabulary.
AUDIO_LLM_START = 151696

# ========================
# 2. Load the BPE -> pieces mapping.
# ========================

def load_bpe_pieces(mapping_path: str):
    """
    Read the JSONL generated by decode_vocab_to_ints.py.
    Each line is {"token_id": int, "pieces": [int, ...], ...}.
    Returns {token_id: pieces}.
    """
    mapping = {}
    with open(mapping_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            obj = json.loads(line)
            tid = obj["token_id"]
            pieces = obj["pieces"]
            mapping[tid] = pieces
    return mapping


# ========================
# 3. Main logic, compatible with tokenizer and embedding size mismatches.
# ========================

def main():
    parser = argparse.ArgumentParser(description="Extend Step-Audio-2-mini with mean-initialized BPE speech tokens.")
    parser.add_argument("--base-model", required=True, help="Local Step-Audio-2-mini checkpoint directory.")
    parser.add_argument("--output", required=True)
    parser.add_argument("--bpe-mapping", required=True, help="JSONL produced by decode_vocab_to_ints.py.")
    args = parser.parse_args()
    BASE_MODEL_DIR = args.base_model
    OUTPUT_MODEL_DIR = args.output
    BPE_MAPPING_JSONL = args.bpe_mapping
    if Path(BASE_MODEL_DIR).resolve() == Path(OUTPUT_MODEL_DIR).resolve():
        parser.error("--output must differ from --base-model")

    # ---- 3.1 Load BPE mapping ----
    print("Loading BPE mapping from:", BPE_MAPPING_JSONL)
    bpe2pieces = load_bpe_pieces(BPE_MAPPING_JSONL)

    if not bpe2pieces:
        raise ValueError("The BPE mapping is empty")
    BPE_VOCAB_SIZE = len(bpe2pieces)
    NEW_AUDIO_TOKENS = BPE_VOCAB_SIZE - AUDIO_BASE_SIZE
    if set(bpe2pieces) != set(range(BPE_VOCAB_SIZE)) or NEW_AUDIO_TOKENS < 1:
        raise ValueError("Expected contiguous BPE IDs with more than 6656 entries")
    for bpe_id, pieces in bpe2pieces.items():
        if not pieces or any(not isinstance(p, int) or not 0 <= p < AUDIO_BASE_SIZE for p in pieces):
            raise ValueError(f"Invalid original speech-token expansion for BPE ID {bpe_id}")
        if bpe_id < AUDIO_BASE_SIZE and pieces != [bpe_id]:
            raise ValueError("Base BPE IDs must match original speech IDs")
    max_bpe_id = max(bpe2pieces.keys())
    min_bpe_id = min(bpe2pieces.keys())
    print(f"  bpe_id range: [{min_bpe_id}, {max_bpe_id}]")
    assert min_bpe_id == 0, "Expected bpe_id to start from 0"
    assert max_bpe_id + 1 >= BPE_VOCAB_SIZE, "BPE_VOCAB_SIZE may be smaller than the actual vocab size"

    # ---- 3.2 Load tokenizer and model ----
    print("Loading base tokenizer & model from:", BASE_MODEL_DIR)
    tokenizer = AutoTokenizer.from_pretrained(
        BASE_MODEL_DIR,
        trust_remote_code=True
    )
    # These validated definitions support training loss and embedding resizing.
    # Registering them bundles the source with save_pretrained checkpoints.
    StepAudio2Config.register_for_auto_class("AutoConfig")
    StepAudio2ForCausalLM.register_for_auto_class("AutoModelForCausalLM")
    config = StepAudio2Config.from_pretrained(BASE_MODEL_DIR)
    model = StepAudio2ForCausalLM.from_pretrained(
        BASE_MODEL_DIR,
        config=config,
        torch_dtype=torch.bfloat16  # Change to float16 / float32 if needed.
    )

    # --- 3.3 Inspect tokenizer / embedding status ---
    emb = model.get_input_embeddings()
    old_num_embeddings, hidden_size = emb.weight.shape

    vocab = tokenizer.get_vocab()  # {token_str: id}
    orig_tok_len = len(vocab)      # Example: 158352.
    orig_max_id = max(vocab.values())  # 158351

    print("Tokenizer:")
    print(f"  len(vocab) = {orig_tok_len}")
    print(f"  max_id     = {orig_max_id}")
    print("Model embedding:")
    print(f"  num_embeddings = {old_num_embeddings}")

    # Ensure the largest tokenizer id does not exceed the number of embedding rows.
    assert orig_max_id < old_num_embeddings, (
        f"tokenizer max id {orig_max_id} >= embedding rows {old_num_embeddings}"
    )

    # Verify that the audio base-unit range is valid.
    assert AUDIO_LLM_START + AUDIO_BASE_SIZE <= old_num_embeddings, (
        f"AUDIO_LLM_START({AUDIO_LLM_START}) + {AUDIO_BASE_SIZE} exceeds embedding rows {old_num_embeddings}"
    )

    # ---- 3.4 Add new tokens to the tokenizer ----
    new_token_strings = [f"<audio_{i}>" for i in range(AUDIO_BASE_SIZE, BPE_VOCAB_SIZE)]
    print(f"Adding {len(new_token_strings)} new audio tokens to tokenizer...")
    added = tokenizer.add_tokens(new_token_strings, special_tokens=False)
    print("  actually added:", added)
    assert added == NEW_AUDIO_TOKENS, "add_tokens count does not match the added BPE vocabulary"

    vocab_after = tokenizer.get_vocab()
    new_tok_len = len(vocab_after)
    new_max_id = max(vocab_after.values())

    print("After add_tokens:")
    print(f"  len(vocab) = {new_tok_len}")
    print(f"  max_id     = {new_max_id}")

    # This handles cases where the embedding matrix is larger than the tokenizer.
    # old_num_embeddings = 158720
    # new_tok_len        = 158352 + 80000 = 238352
    # new_max_id         = 158351 + 80000 = 238351
    # The new embedding row count must cover at least new_max_id + 1.
    new_num_embeddings = max(old_num_embeddings, new_max_id + 1)
    print(f"Resizing token embeddings from {old_num_embeddings} to {new_num_embeddings} ...")
    model.resize_token_embeddings(new_num_embeddings, mean_resizing=False)
    model.config.text_config.vocab_size = new_num_embeddings

    # Fetch embedding and lm_head again.
    emb = model.get_input_embeddings()
    print("New embedding shape:", emb.weight.shape)

    out_proj = model.get_output_embeddings()
    tied = False
    if out_proj is not None:
        tied = (out_proj.weight.data.data_ptr() == emb.weight.data.data_ptr())
    print("LM head present:", out_proj is not None, "  tied with embedding:", tied)

    emb_dtype = emb.weight.dtype
    out_dtype = out_proj.weight.dtype if out_proj is not None else None

    # ---- 3.5 Initialize new token weights by averaging BPE pieces ----
    print("Initializing new audio token weights from base audio tokens...")

    for bpe_id in range(AUDIO_BASE_SIZE, BPE_VOCAB_SIZE):
        pieces = bpe2pieces.get(bpe_id, None)
        if pieces is None:
            raise ValueError(f"bpe_id {bpe_id} cannot find pieces in the BPE mapping file")

        if len(pieces) == 0:
            raise ValueError(f"bpe_id {bpe_id} has empty pieces; data is abnormal")

        # Map base audio ids in BPE to global ids in the model embedding.
        base_llm_ids = [AUDIO_LLM_START + p for p in pieces]
        for gid in base_llm_ids:
            if not (0 <= gid < old_num_embeddings):
                raise ValueError(
                    f"base audio global id {gid} is out of range (0..{old_num_embeddings-1}); "
                    f"please check AUDIO_LLM_START / AUDIO_BASE_SIZE settings"
                )

        # Compute the average embedding.
        base_emb = emb.weight.data[base_llm_ids].float()   # [n_pieces, hidden_size]
        mean_emb = base_emb.mean(dim=0)                    # [hidden_size]

        # New token id in the tokenizer / model; it no longer assumes ids start at old_num_embeddings.
        new_token_str = f"<audio_{bpe_id}>"
        new_llm_id = tokenizer.convert_tokens_to_ids(new_token_str)

        # Write to the embedding matrix.
        emb.weight.data[new_llm_id] = mean_emb.to(emb_dtype)

        # If lm_head exists and is not tied, apply the same update to lm_head.
        if out_proj is not None and not tied:
            base_out = out_proj.weight.data[base_llm_ids].float()
            mean_out = base_out.mean(dim=0)
            out_proj.weight.data[new_llm_id] = mean_out.to(out_dtype)

    print("All new audio token weights initialized.")

    # ---- 3.6 Save the expanded model and tokenizer ----
    out_dir = Path(OUTPUT_MODEL_DIR)
    out_dir.mkdir(parents=True, exist_ok=True)

    print("Saving extended tokenizer to:", out_dir)
    tokenizer.save_pretrained(out_dir)

    print("Saving extended model to:", out_dir)
    model.save_pretrained(out_dir)

    # ---- 3.7 Also save the BPE-id -> LLM-id mapping for later inference ----
    mapping_path = out_dir / "audio_bpeid_to_llmid.json"
    bpeid_to_llmid = {}

    # base 0..6655
    for bpe_id in range(AUDIO_BASE_SIZE):
        bpeid_to_llmid[bpe_id] = AUDIO_LLM_START + bpe_id

    # new 6656..86655
    for bpe_id in range(AUDIO_BASE_SIZE, BPE_VOCAB_SIZE):
        tok = f"<audio_{bpe_id}>"
        bpeid_to_llmid[bpe_id] = tokenizer.convert_tokens_to_ids(tok)

    with mapping_path.open("w", encoding="utf-8") as f:
        json.dump(bpeid_to_llmid, f, ensure_ascii=False, indent=2)

    print("Saved BPE-id -> LLM-id mapping to:", mapping_path)
    print("Done.")


if __name__ == "__main__":
    main()
